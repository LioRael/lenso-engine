import { createHash, randomUUID } from "node:crypto";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const [entryArgument, artifactArgument, reportArgument, profile = "development"] = Bun.argv.slice(2);
if (!entryArgument || !artifactArgument || !reportArgument || !["development", "release"].includes(profile)) {
  throw new Error("expected Plugin entry, artifact output, report output, and development|release profile");
}
const root = process.cwd();
const entry = fs.realpathSync(path.resolve(root, entryArgument));
const artifact = path.resolve(root, artifactArgument);
const report = path.resolve(root, reportArgument);
const requireFromPlugin = createRequire(entry);
const resolveFromPlugin = (specifier) => requireFromPlugin.resolve(specifier);
const importFromPlugin = async (specifier) =>
  import(pathToFileURL(resolveFromPlugin(specifier)).href);
const extraction = await importFromPlugin("@lenso/bun-plugin/extract");
const buildApi = await importFromPlugin("@lenso/bun-plugin/build");

const lockPath = path.join(root, "bun.lock");
const lockText = fs.readFileSync(lockPath, "utf8");
let lock;
if (typeof Bun.JSONC?.parse !== "function") {
  throw new Error("Plugin builds require Bun with JSONC support; use Bun 1.4.0 or newer");
}
try {
  lock = Bun.JSONC.parse(lockText);
} catch {
  throw new Error(`${lockPath}: invalid Bun lockfile`);
}
if (!lock || typeof lock !== "object" || Array.isArray(lock)) {
  throw new Error(`${lockPath}: invalid Bun lockfile`);
}
const packageCache = new Map();
const packagesByIdentity = new Map();
const lockedPackages = new Map();
const contractArtifacts = new Map();
const generatedProviderDescriptors = new Map();

function packageForFile(filename) {
  const real = fs.realpathSync(filename);
  const cached = packageCache.get(real);
  if (cached) return cached;
  let directory = path.dirname(real);
  while (directory !== path.dirname(directory)) {
    const manifestPath = path.join(directory, "package.json");
    if (fs.existsSync(manifestPath)) {
      const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
      if (typeof manifest.name === "string" && typeof manifest.version === "string") {
        const identity = lockedIdentity(manifest.name, manifest.version);
        const info = { directory, manifest, identity };
        packageCache.set(real, info);
        packagesByIdentity.set(identityKey(identity), info);
        return info;
      }
    }
    directory = path.dirname(directory);
  }
  throw new Error(`${filename}: declaration origin is outside an exact package`);
}

function lockedIdentity(name, version) {
  const entries = Object.values(lock.packages ?? {}).filter((candidate) =>
    Array.isArray(candidate) && candidate[0] === `${name}@${version}`,
  );
  if (entries.length !== 1 || typeof entries[0][3] !== "string") {
    throw new Error(`${name}@${version}: package is not selected once with registry integrity in bun.lock`);
  }
  return Object.freeze({ name, version, integrity: entries[0][3] });
}

function identityKey(identity) {
  return `${identity.name}\0${identity.version}\0${identity.integrity}`;
}

function exportSubpath(info, origin) {
  const specifier = origin.module;
  const subpath = specifier === info.manifest.name
    ? "."
    : specifier?.startsWith(`${info.manifest.name}/`)
      ? `./${specifier.slice(info.manifest.name.length + 1)}`
      : undefined;
  const exports = info.manifest.exports ?? {};
  const exported = subpath !== undefined && (
    Object.prototype.hasOwnProperty.call(exports, subpath) ||
    Object.keys(exports).some((candidate) => {
      const wildcard = candidate.indexOf("*");
      return wildcard >= 0 &&
        candidate.indexOf("*", wildcard + 1) < 0 &&
        subpath.startsWith(candidate.slice(0, wildcard)) &&
        subpath.endsWith(candidate.slice(wildcard + 1));
    })
  );
  if (!exported) {
    throw new Error(`${origin.file}: declaration origin is not a public package export`);
  }
  return subpath;
}

function generatedContract(origin, local) {
  const runtimeFile = origin.file.endsWith(".d.ts")
    ? origin.file.slice(0, -".d.ts".length) + ".js"
    : origin.file;
  if (!fs.existsSync(runtimeFile)) {
    throw new Error(`${origin.file}: generated contract has no runtime module`);
  }
  const source = fs.readFileSync(runtimeFile, "utf8");
  if (!source.startsWith("/* @generated by lenso-contract-codegen; do not edit. */")) return undefined;
  const modern = source.match(/export\s+const\s+(\w+)(?:\s*:[^=]+)?\s*=\s*\{\s*kind:\s*"lenso.capability"/u);
  if (!origin.name.endsWith("_CONTRACT") && origin.name !== modern?.[1]) return undefined;
  const read = (name) => {
    const match = source.match(
      new RegExp(`export\\s+const\\s+${name}\\s*=\\s*[\"']([^\"']+)[\"']`, "u"),
    );
    if (!match) throw new Error(`${runtimeFile}: generated contract is missing ${name}`);
    return match[1];
  };
  let artifactPath;
  if (local) {
    artifactPath = path.relative(root, fs.realpathSync(runtimeFile)).replaceAll(path.sep, "/");
  } else {
    const info = packageForFile(origin.file);
    exportSubpath(info, origin);
    const relative = path.relative(info.directory, fs.realpathSync(runtimeFile)).replaceAll(path.sep, "/");
    lockedPackages.set(identityKey(info.identity), info.identity);
    artifactPath = `${info.identity.name}@${info.identity.version}/${relative}`;
  }
  contractArtifacts.set(artifactPath, digest(source));
  if (modern) {
    const descriptor = source.match(/descriptor:\s*\{([^}]+)\}/u)?.[1];
    const operations = (name) => {
      const match = descriptor?.match(new RegExp(`(?:^|[,\\s])${name}:\\s*(\\[[^\\]]*\\])`, "u"));
      if (!match) throw new Error(`${runtimeFile}: generated contract is missing ${name}`);
      const values = JSON.parse(match[1]);
      if (!Array.isArray(values) || values.some((value) => typeof value !== "string")) throw new Error(`${runtimeFile}: invalid generated ${name}`);
      return values;
    };
    generatedProviderDescriptors.set(`${pathToFileURL(runtimeFile).href}#${origin.name}`, {
      request_operations: operations("operations").filter(name => !operations("stream_operations").includes(name) && !operations("event_operations").includes(name)), stream_operations: operations("stream_operations"), event_operations: operations("event_operations"),
    });
  }
  return {
    kind: "contract",
    capability_id: read("CAPABILITY_ID"),
    descriptor_version: read("DESCRIPTOR_VERSION"),
    descriptor_digest: read("DESCRIPTOR_DIGEST"),
    generated_module: pathToFileURL(runtimeFile).href,
    generated_export: origin.name,
  };
}

function classifySymbol(origin) {
  const originFile = fs.realpathSync(origin.file);
  const local =
    originFile.startsWith(`${root}${path.sep}`) &&
    !originFile.includes(`${path.sep}node_modules${path.sep}`);
  const contract = generatedContract(origin, local);
  if (contract) return contract;
  if (local) return undefined;
  const info = packageForFile(origin.file);
  const subpath = exportSubpath(info, origin);
  if (info.manifest.name === "@lenso/bun-plugin" && subpath === ".") {
    if (origin.name === "definePlugin") return { kind: "plugin_definition" };
    if (origin.name === "dependency" || origin.name === "configuration" || origin.name === "provider") {
      lockedPackages.set(identityKey(info.identity), info.identity);
      return {
        kind: "declaration",
        package: info.identity,
        export_name: origin.name,
        ...(origin.name === "configuration" || origin.name === "provider"
          ? { handler_parameters: [1] }
          : {}),
      };
    }
  }
  const rawMetadata = info.manifest.lenso?.build;
  if (!rawMetadata) return undefined;
  const metadata = buildApi.validateBuildPackageMetadata(rawMetadata);
  const declarations = metadata.declarations[subpath];
  if (!declarations?.includes(origin.name)) return undefined;
  info.buildMetadata = metadata;
  lockedPackages.set(identityKey(info.identity), info.identity);
  return {
    kind: "declaration",
    package: info.identity,
    export_name: origin.name,
    ...(metadata.handler_parameters?.[subpath]?.[origin.name]
      ? { handler_parameters: metadata.handler_parameters[subpath][origin.name] }
      : {}),
  };
}

const definition = await extraction.extractPluginDefinition({
  entryFile: entry,
  classifySymbol,
});
const configurationSchema = compileConfiguration(definition.config);

const loweredProviders = [];
const generatedFiles = new Map();
const handlerArguments = new Map();
for (const provider of definition.providers) {
  if (provider.kind === "contract") {
    const descriptor = generatedProviderDescriptors.get(`${provider.generated_module}#${provider.generated_export}`);
    if (!descriptor || descriptor.event_operations.length) {
      throw new Error(`${provider.span.file}: provides requires a generated Request/Stream Capability supported by this build profile`);
    }
    const binderPath = `generic/provider-${loweredProviders.length}.ts`;
    generatedFiles.set(binderPath, [
      `import { ${provider.generated_export} as contract } from ${JSON.stringify(fileURLToPath(provider.generated_module))};`,
      `export function bindProvider(instance) { return contract.bindProvider(instance); }`,
    ].join("\n"));
    loweredProviders.push({
      capability_id: provider.capability_id, descriptor_version: provider.descriptor_version,
      descriptor_digest: provider.descriptor_digest, request_operations: descriptor.request_operations,
      stream_operations: descriptor.stream_operations,
      binder: { module: binderPath, export_name: "bindProvider" },
    });
    continue;
  }
  if (provider.kind !== "declaration") {
    throw new Error(`${provider.span.file}: providers must come from a package declaration lowering`);
  }
  const info = packagesByIdentity.get(identityKey(provider.package));
  if (provider.package.name === "@lenso/bun-plugin" && provider.export_name === "provider") {
    collectHandlers(provider.arguments, handlerArguments);
    const descriptorArgument = provider.arguments[0];
    const binderArgument = provider.arguments[1];
    if (provider.arguments.length !== 2 || descriptorArgument?.kind !== "value" || !isRecord(descriptorArgument.value) || binderArgument?.kind !== "handler") {
      throw new Error(`${provider.span.file}: provider requires one static descriptor and one binder function`);
    }
    const descriptor = plainStatic(descriptorArgument, "provider descriptor");
    const capabilityId = descriptor.capability_id;
    const descriptorVersion = descriptor.descriptor_version;
    const descriptorDigest = descriptor.descriptor_digest;
    const requestOperations = descriptor.operations;
    const streamOperations = descriptor.stream_operations;
    const eventOperations = descriptor.event_operations;
    if (
      typeof capabilityId !== "string" ||
      typeof descriptorVersion !== "string" ||
      typeof descriptorDigest !== "string" ||
      !Array.isArray(requestOperations) || requestOperations.some((value) => typeof value !== "string") ||
      !Array.isArray(streamOperations) || streamOperations.some(value => typeof value !== "string") ||
      !Array.isArray(eventOperations) || eventOperations.length !== 0
    ) {
      throw new Error(`${provider.span.file}: provider descriptor must declare one Request/Stream Capability with an exact digest`);
    }
    const binderPath = `generic/provider-${loweredProviders.length}.ts`;
    generatedFiles.set(binderPath, [
      `import { resolveHandler } from "lenso:build-handlers";`,
      `const bind = resolveHandler(${JSON.stringify(binderArgument.reference)});`,
      `export function bindProvider(instance) { return bind(instance); }`,
    ].join("\n"));
    loweredProviders.push({
      capability_id: capabilityId,
      descriptor_version: descriptorVersion,
      descriptor_digest: descriptorDigest,
      request_operations: requestOperations.filter(operation => !streamOperations.includes(operation)),
      stream_operations: streamOperations,
      binder: { module: binderPath, export_name: "bindProvider" },
    });
    continue;
  }
  const metadata = info?.buildMetadata ??
    (info?.manifest.lenso?.build
      ? buildApi.validateBuildPackageMetadata(info.manifest.lenso.build)
      : undefined);
  if (!info || !metadata) {
    throw new Error(`${provider.package.name}: declaration package has no validated lenso.build metadata`);
  }
  const buildSpecifier = `${provider.package.name}${metadata.export.slice(1)}`;
  const buildModulePath = resolveFromPlugin(buildSpecifier);
  if (!fs.realpathSync(buildModulePath).startsWith(`${info.directory}${path.sep}`)) {
    throw new Error(`${provider.package.name}: build export resolved outside its locked package`);
  }
  const buildModule = await import(pathToFileURL(buildModulePath).href);
  if (typeof buildModule.lower !== "function") {
    throw new Error(`${provider.package.name}: build export has no lower function`);
  }
  collectHandlers(provider.arguments, handlerArguments);
  const input = Object.freeze({
    api_version: 1,
    package: provider.package,
    export_name: provider.export_name,
    arguments: provider.arguments,
    span: provider.span,
  });
  const output = await buildApi.runLowering(buildModule.lower, input, {
    allowedProviders: metadata.provider_contracts,
  });
  for (const diagnostic of output.diagnostics) {
    const message = `${diagnostic.span.file}:${diagnostic.span.start}: ${diagnostic.message}`;
    if (diagnostic.severity === "error") throw new Error(message);
    console.error(`warning: ${message}`);
  }
  for (const file of output.files) {
    if (generatedFiles.has(file.path)) throw new Error(`duplicate generated path ${file.path}`);
    generatedFiles.set(file.path, file.contents);
  }
  for (const lowered of output.providers) {
    const contract = metadata.provider_contracts.find((candidate) =>
      candidate.capability_id === lowered.capability_id &&
      candidate.descriptor_version === lowered.descriptor_version &&
      candidate.descriptor_digest === lowered.descriptor_digest,
    );
    if (!contract) throw new Error(`lowering returned an undeclared provider contract`);
    loweredProviders.push({ ...lowered, request_operations: contract.request_operations });
  }
  lockedPackages.set(identityKey(provider.package), provider.package);
}

const requiredCapabilities = Object.entries(definition.dependencies ?? {}).map(([name, value]) => {
  const modern = value.kind === "value" && value.value?.kind === "lenso.dependency";
  if (!modern && (value.kind !== "declaration" || value.package.name !== "@lenso/bun-plugin" || value.export_name !== "dependency")) {
    throw new Error(`${value.span.file}: dependency ${name} must use a generated Capability or dependency declaration`);
  }
  const options = modern ? value : value.arguments[0];
  if ((!modern && value.arguments.length !== 1) || options?.kind !== "value" || !isRecord(options.value)) {
    throw new Error(`${value.span.file}: dependency ${name} requires static options`);
  }
  const id = modern && options.value.id === undefined ? name : staticValue(options.value.id);
  const cardinality = options.value.cardinality === undefined
    ? "one"
    : staticValue(options.value.cardinality);
  const contract = options.value.contract;
  if (id !== name) throw new Error(`${value.span.file}: dependency key and public id must both be ${name}`);
  if (!["one", "optional", "many"].includes(cardinality)) {
    throw new Error(`${value.span.file}: dependency ${name} has invalid cardinality`);
  }
  if (!isRecord(contract) || contract.kind !== "contract") {
    throw new Error(`${value.span.file}: dependency ${name} requires one generated *_CONTRACT reference`);
  }
  return {
    requirement_id: id,
    capability_id: contract.capability_id,
    descriptor_version: contract.descriptor_version,
    cardinality,
  };
});

const stage = path.join(path.dirname(artifact), `.lenso-bun-build-${randomUUID()}`);
fs.mkdirSync(stage, { recursive: false });
for (const [relative, contents] of generatedFiles) {
  const destination = path.join(stage, relative);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, contents);
}
const binderImports = [];
const binderValues = [];
for (const [index, provider] of loweredProviders.entries()) {
  const modulePath = path.join(stage, provider.binder.module);
  binderImports.push(`import { ${provider.binder.export_name} as binder${index} } from ${JSON.stringify(modulePath)};`);
  binderValues.push(`{ kind: "lenso.provider", descriptor: ${JSON.stringify({
    capability_id: provider.capability_id,
    descriptor_version: provider.descriptor_version,
    descriptor_digest: provider.descriptor_digest,
    operations: [...provider.request_operations, ...(provider.stream_operations ?? [])],
    stream_operations: provider.stream_operations ?? [],
    event_operations: [],
  })}, bind: binder${index} }`);
}
const wrapper = path.join(stage, "entry.ts");
fs.writeFileSync(wrapper, [
  `import definition from ${JSON.stringify(entry)};`,
  `import { servePluginV2 } from "@lenso/bun-plugin";`,
  ...binderImports,
  `await servePluginV2({ ...definition, providers: [${binderValues.join(",")}] });`,
].join("\n"));

const handlerModules = new Map();
for (const [index, [reference, span]] of [...handlerArguments].entries()) {
  const values = handlerModules.get(span.file) ?? [];
  values.push({ reference, span, exportName: `__lenso_build_handler_${index}` });
  handlerModules.set(span.file, values);
}
const virtualHandlers = [...handlerModules].flatMap(([file, handlers]) => {
  const names = handlers.map(({ exportName }) => exportName).join(", ");
  return [`import { ${names} } from ${JSON.stringify(file)};`, ...handlers.map(({ reference, exportName }) => `[${JSON.stringify(reference)}, ${exportName}],` )];
});
const linker = {
  name: "lenso-build-handlers",
  setup(builder) {
    builder.onResolve({ filter: /^@lenso\// }, ({ path: specifier }) => ({
      path: resolveFromPlugin(specifier),
    }));
    builder.onResolve({ filter: /^lenso:build-handlers$/ }, () => ({ path: "handlers", namespace: "lenso" }));
    builder.onLoad({ filter: /.*/, namespace: "lenso" }, () => ({
      loader: "ts",
      contents: `${virtualHandlers.filter((line) => line.startsWith("import ")).join("\n")}\nconst handlers = new Map([${virtualHandlers.filter((line) => line.startsWith("[")).join("\n")}]);\nexport function resolveHandler(reference) { const handler = handlers.get(reference); if (!handler) throw new Error(\`unknown linked handler \${reference}\`); return handler; }`,
    }));
    builder.onLoad({ filter: /\.[cm]?[jt]sx?$/ }, ({ path: filename }) => {
      const handlers = handlerModules.get(filename);
      if (!handlers) return undefined;
      const source = fs.readFileSync(filename, "utf8");
      const appended = handlers.map(({ span, exportName }) =>
        `export const ${exportName} = (${source.slice(span.start, span.end)});`,
      );
      return { loader: loaderFor(filename), contents: `${source}\n${appended.join("\n")}` };
    });
  },
};
const result = await Bun.build({
  entrypoints: [wrapper],
  target: "bun",
  format: "esm",
  minify: profile === "release",
  external: ["bun", "node:*"],
  plugins: [linker],
});
if (!result.success || result.outputs.length !== 1) {
  throw new Error(`Bun Plugin build failed: ${result.logs.map(String).join("\n")}`);
}
fs.mkdirSync(path.dirname(artifact), { recursive: true });
await Bun.write(artifact, result.outputs[0]);

const sourceClosure = definition.sourceFiles
  .filter((filename) => path.resolve(filename).startsWith(`${root}${path.sep}`) && !filename.includes(`${path.sep}node_modules${path.sep}`))
  .map((filename) => ({ path: path.relative(root, filename).replaceAll(path.sep, "/"), sha256: digest(fs.readFileSync(filename)) }));
const fingerprint = buildApi.fingerprintBuildInputs({
  sourceClosure,
  contractArtifacts: [...contractArtifacts].map(([path, sha256]) => ({ path, sha256 })),
  lockedPackages: [...lockedPackages.values()],
  target: `bun-${process.platform}-${process.arch}`,
});
fs.writeFileSync(report, JSON.stringify({
  fingerprint,
  descriptor: {
    abi: requiredCapabilities.length === 0
      ? (loweredProviders.some(p => p.stream_operations?.length) ? "lenso.json-interactions@1" : "lenso.json-request@1")
      : "lenso.json-host-imports@2",
    ...(configurationSchema === undefined ? {} : { configuration_schema: configurationSchema }),
    capabilities: loweredProviders.map((provider) => ({
      capability_id: provider.capability_id,
      descriptor_version: provider.descriptor_version,
      descriptor_digest: provider.descriptor_digest,
      request_operations: provider.request_operations,
      stream_operations: provider.stream_operations ?? [],
    })),
    required_capabilities: requiredCapabilities,
  },
}));

function collectHandlers(arguments_, output) {
  for (const argument of arguments_) {
    if (argument.kind === "handler") output.set(argument.reference, argument.span);
    if (argument.kind === "declaration") collectHandlers(argument.arguments, output);
    if (argument.kind === "value") collectValueHandlers(argument.value, output);
  }
}

function compileConfiguration(declaration) {
  if (declaration === undefined) return undefined;
  if (
    declaration.kind !== "declaration" ||
    declaration.package.name !== "@lenso/bun-plugin" ||
    declaration.export_name !== "configuration"
  ) {
    throw new Error(`${declaration.span.file}: config must use the generic configuration declaration`);
  }
  if (declaration.arguments.length !== 2 || declaration.arguments[1]?.kind !== "handler") {
    throw new Error(`${declaration.span.file}: configuration requires one static schema and one decoder`);
  }
  const schema = plainStatic(declaration.arguments[0], "configuration schema");
  if (!isRecord(schema) && typeof schema !== "boolean") {
    throw new Error(`${declaration.span.file}: configuration schema must be a JSON Schema object or boolean`);
  }
  return schema;
}

function collectValueHandlers(value, output) {
  if (Array.isArray(value)) return value.forEach((item) => collectValueHandlers(item, output));
  if (!isRecord(value)) return;
  if (value.kind === "handler") {
    output.set(value.reference, value.span);
    return;
  }
  if (value.kind === "declaration") {
    collectHandlers(value.arguments, output);
    return;
  }
  for (const child of Object.values(value)) collectValueHandlers(child, output);
}

function staticValue(value) {
  return isRecord(value) && value.kind === "value" ? value.value : value;
}

function plainStatic(argument, subject) {
  if (!isRecord(argument) || argument.kind !== "value") {
    throw new Error(`${subject} must contain only static JSON values`);
  }
  return plainStaticPayload(argument.value, subject);
}

function plainStaticPayload(value, subject) {
  if (Array.isArray(value)) return value.map((item) => plainStatic(item, subject));
  if (!isRecord(value)) return value;
  return Object.fromEntries(
    Object.entries(value).map(([name, item]) => [name, plainStatic(item, `${subject}.${name}`)]),
  );
}

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function loaderFor(filename) {
  if (filename.endsWith(".tsx")) return "tsx";
  if (filename.endsWith(".jsx")) return "jsx";
  if (filename.endsWith(".js") || filename.endsWith(".mjs") || filename.endsWith(".cjs")) return "js";
  return "ts";
}

function digest(bytes) {
  return `sha256:${createHash("sha256").update(bytes).digest("hex")}`;
}
